def _column_type(spec: tuple[object, ...]) -> sa.types.TypeEngine:
    kind = spec[0]
    if kind == "string":
        return sa.String(spec[1])
    if kind == "boolean":
        return sa.Boolean()
    if kind == "integer":
        return sa.Integer()
    if kind == "float":
        return sa.Float()
    if kind == "numeric":
        return sa.Numeric(precision=spec[1], scale=spec[2])
    if kind == "json":
        return sa.JSON()
    raise ValueError(f"Unsupported frozen column type: {kind!r}")


def _columns(specs: tuple[tuple[object, ...], ...]) -> list[sa.Column]:
    return [
        sa.Column(
            name,
            _column_type(type_definition),
            nullable=nullable,
            primary_key=primary_key,
        )
        for name, type_definition, nullable, primary_key in specs
    ]


def _constraint(spec: tuple[object, ...]) -> sa.Constraint:
    kind = spec[0]
    if kind == "foreign_key":
        _, name, columns, target_table, target_columns, ondelete = spec
        return sa.ForeignKeyConstraint(
            columns,
            [f"{target_table}.{column}" for column in target_columns],
            name=name,
            ondelete=ondelete,
        )
    if kind == "unique":
        _, name, columns = spec
        return sa.UniqueConstraint(*columns, name=name)
    if kind == "check":
        _, name, expression = spec
        return sa.CheckConstraint(expression, name=name)
    raise ValueError(f"Unsupported frozen constraint: {kind!r}")


